std::string MorseCode::CharToMorse(char C)
{
    auto It = MorseMap.find(C);
    if (It != MorseMap.end())
    {
        return It->second;
    }
    return ""; // Âîçâðàùàåì ïóñòóþ ñòðîêó äëÿ íåèçâåñòíûõ ñèìâîëîâ
}

bool MorseCode::IsValidInput(const std::string& Text)
{
    for (char C : Text)
    {
        if (C != ' ' && MorseMap.find(C) == MorseMap.end())
        {
            return false;
        }
    }
    return true;
}

std::string MorseCode::TextToMorse(const std::string& Text)
{
    std::string Result;
    for (size_t i = 0; i < Text.length(); ++i)
    {
        char C = Text[i];
        if (C == ' ')
        {
            Result += "  "; // Äâà ïðîáåëà ìåæäó ñëîâàìè
        }
        else
        {
            std::string MorseChar = CharToMorse(C);
            if (!MorseChar.empty())
            {
                Result += MorseChar + " "; // Ïðîáåë ìåæäó áóêâàìè
            }
        }
    }
    return Result;
}
